import re

STRENGTH_STEPS = (420, 460, 490, 550, 690, 890)


def step_for(mpa):
    """Округлить предел текучести вниз к ступени мониторинга; None если < 420."""
    best = None
    for s in STRENGTH_STEPS:
        if mpa >= s:
            best = s
    return best


